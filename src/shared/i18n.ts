const dictionaries: Record<Lang, Record<I18nKey, string>> = { en, tr }

/** anahtar + isteğe bağlı parametrelerle çeviriyi çöz */
export function translate(lang: Lang, key: I18nKey, params?: Record<string, string | number>): string {
  const dict = dictionaries[lang] ?? en
  let s: string = dict[key] ?? en[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v))
    }
  }
  return s
}

export const i18n = { translate, dictionaries }


